import process from "node:process";
import console from "node:console";
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
const require = createRequire(import.meta.url);
const result = await build({
  entryPoints: ["scripts/content/native-search-entry.mjs"],
  bundle: true, write: false, metafile: true, format: "iife", platform: "browser", minify: true,
});
const allowedInputs = new Set([
  "scripts/content/native-search-entry.mjs", "packages/core/src/native-search-worker.ts",
  "packages/core/src/native-search.ts", "packages/core/src/discovery.ts", "packages/core/src/search.ts",
  "node_modules/fuse.js/dist/fuse.mjs",
]);
for (const path of Object.keys(result.metafile.inputs)) {
  if (!allowedInputs.has(path)) throw new Error(`Unexpected native search runtime dependency: ${path}`);
}
const license = await readFile(resolve(dirname(dirname(require.resolve("fuse.js"))), "LICENSE"), "utf8");
const runtime = `/*! Fuse.js\n${license.replaceAll("*/", "* /")}\n*/\n${result.outputFiles[0].text}`;
const output = `// Generated by npm run search:runtime. Do not edit.\nexport const nativeSearchWorkerSource = ${JSON.stringify(runtime)};\n`;
const path = "apps/mobile/src/generated/search-worker.ts";
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8") !== output) throw new Error("Native search runtime is stale; run npm run search:runtime");
  console.log("Native local search runtime is current.");
} else {
  await writeFile(path, output);
  console.log(`Bundled offline native search (${runtime.length} characters).`);
}
